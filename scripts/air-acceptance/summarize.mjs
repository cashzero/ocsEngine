// Collects every run folder's results.json under an evidence directory into one README table per run.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const dir = process.argv[2] ?? 'artifacts/air-2026-10-03';
const cell = (text) => String(text ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').slice(0, 420);
const sections = [];
for (const run of (await readdir(dir, { withFileTypes: true })).filter((entry) => entry.isDirectory()).map(({ name }) => name).sort()) {
  const results = JSON.parse(await readFile(join(dir, run, 'results.json'), 'utf8').catch(() => 'null'));
  if (!results) continue;
  const files = (await readdir(join(dir, run))).filter((name) => /\.(jpg|png|json)$/.test(name) && name !== 'results.json');
  const passed = results.rows.filter(({ status }) => status === 'PASS').length;
  const timings = (results.timings ?? []).map(({ label, elapsed }) => `${label}: ${elapsed} ms`).join('; ') || 'none recorded';
  const final = results.final ? `${results.final.turn}, ${results.final.player}, ${results.final.phase}${results.final.revision ? `, final revision ${results.final.revision}` : ''}` : 'not recorded';
  sections.push(`## ${run} — ${results.title}

${passed} of ${results.rows.length} checks passed · console/page errors: ${results.errors.length} · ended at: ${final}

Timed actions: ${timings}

| Row | Expectation | Observed | Result |
|---|---|---|---|
${results.rows.map((row) => `| ${row.id} | ${cell(row.expectation)} | ${cell(row.observed)} | ${row.status} |`).join('\n')}

Inputs and every step: [log.md](${run}/log.md). Artifacts: ${files.map((name) => `[${name}](${run}/${name})`).join(', ')}
`);
}
await writeFile(join(dir, 'RUNS.md'), `# AIR acceptance runs (generated by scripts/air-acceptance/summarize.mjs)\n\n${sections.join('\n')}`);
console.log(`${sections.length} runs summarized into ${join(dir, 'RUNS.md')}`);
